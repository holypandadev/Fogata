REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"


def lock(*packages):
    """A Cargo.lock of (name, version) or (name, version, source) packages."""
    text = "# This file is automatically @generated by Cargo.\nversion = 4\n"
    for package in packages:
        name, version = package[:2]
        text += f'\n[[package]]\nname = "{name}"\nversion = "{version}"\n'
        source = package[2] if len(package) > 2 else REGISTRY
        if source:
            text += f'source = "{source}"\n'
        text += 'dependencies = [\n "x",\n]\n'
    return text


class FuzzLock(unittest.TestCase):
    def test_the_locks_of_the_repository_agree(self):
        root = TOOLS.parent
        self.assertEqual(fuzz_lock.differences((root / "Cargo.lock").read_text(),
                                               (root / "fuzz/Cargo.lock").read_text()), [])

    def test_a_shared_crate_at_another_version_fails(self):
        main = lock(("async-executor", "1.14.1"), ("serde", "1.0.1"))
        fuzz = lock(("async-executor", "1.14.0"), ("serde", "1.0.1"))
        [line] = fuzz_lock.differences(main, fuzz)
        self.assertIn("async-executor 1.14.0", line)
        self.assertIn("Cargo.lock has 1.14.1", line)

    def test_crates_of_the_fuzz_workspace_alone_and_versions_it_lacks_pass(self):
        main = lock(("hashbrown", "0.14.5"), ("hashbrown", "0.17.1"), ("fogata-core", "0.1.0", None))
        fuzz = lock(("hashbrown", "0.17.1"), ("libfuzzer-sys", "0.4.13"),
                    ("fogata-core", "0.1.0", None))
        self.assertEqual(fuzz_lock.differences(main, fuzz), [])

    def test_the_same_version_from_another_source_fails(self):
        main = lock(("turn", "0.17.2", None))
        fuzz = lock(("turn", "0.17.2"))
        self.assertEqual(len(fuzz_lock.differences(main, fuzz)), 1)


def metadata(*packages):
    """cargo metadata's JSON (as a dict) of (name, [(dependency, kind)]) packages."""
    return {"packages": [
        {"name": name, "dependencies": [{"name": d, "kind": kind} for d, kind in deps]}
        for name, deps in packages]}


class CrateLayers(unittest.TestCase):
    def today(self):
        return [(name, [(d, None) for d in sorted(allowed)])
                for name, allowed in crate_layers.ALLOWED.items()]

    def test_the_edges_allowed_keep_to_the_layers(self):
        self.assertEqual(crate_layers.problems(metadata(*self.today())), [])
        self.assertEqual(set(crate_layers.ALLOWED), set(crate_layers.LAYERS))

    def test_a_new_edge_fails(self):
        packages = dict(self.today())
        packages["fogata-net"] = packages["fogata-net"] + [("fogata-media", None)]
        [line] = crate_layers.problems(metadata(*packages.items()))
        self.assertIn("fogata-net has fogata-media as a dependency", line)

    def test_a_crate_with_no_layer_fails(self):
        found = crate_layers.problems(metadata(*self.today(), ("fogata-new", [])))
        self.assertEqual(len(found), 1)
        self.assertIn("fogata-new", found[0])

    def test_a_test_edge_is_allowed_only_for_tests(self):
        dev = metadata(("fogata-media", [("fogata-net", None), ("fogata-state", "dev")]))
        self.assertEqual(crate_layers.problems(dev), [])
        normal = metadata(("fogata-media", [("fogata-net", None), ("fogata-state", None)]))
        self.assertEqual(len(crate_layers.problems(normal)), 1)

    def test_crates_from_outside_are_left_alone(self):
        self.assertEqual(crate_layers.problems(metadata(
            ("fogata-crypto", [("serde", None), ("libp2p-quic", None)]))), [])


class Limits(unittest.TestCase):
    """tools/limits.py on a copy of the files it reads."""

    def setUp(self):
        self.root = pathlib.Path(tempfile.mkdtemp(prefix="fogata-limits-test-"))
        real = TOOLS.parent
        for path in set(limits.RUST.values()) | {p for p, _ in limits.DART_CONSTANTS}:
            (self.root / path).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(real / path, self.root / path)
        screens = self.root / "app/lib/src/screens"
        screens.mkdir(parents=True, exist_ok=True)
        self.field = screens / "field.dart"
        self.field.write_text("FgField(\n  controller: _name,\n  maxLength: 60,\n"
                              "  label: l10n.newGroupName,\n);\n"
                              "FgField(maxLength: maxMessage, label: l10n.chatHint);\n")

    def tearDown(self):
        shutil.rmtree(self.root)

    def edit(self, path, old, new):
        text = (self.root / path).read_text()
        self.assertIn(old, text)
        (self.root / path).write_text(text.replace(old, new))

    def test_the_repository_agrees(self):
        self.assertEqual(limits.problems(TOOLS.parent), [])

    def test_the_copy_agrees(self):
        self.assertEqual(limits.problems(self.root), [])

    def test_a_rust_limit_changed_alone_fails(self):
        self.edit("crates/fogata-state/src/room.rs", "MAX_CHAT_CHARS: usize = 2000;",
                  "MAX_CHAT_CHARS: usize = 4000;")
        [line] = limits.problems(self.root)
        self.assertIn("maxMessage is 2000, MAX_CHAT_CHARS", line)
        self.edit("crates/fogata-state/src/room.rs", "4000", "2000")
        self.edit("crates/fogata-state/src/state.rs", "MAX_GROUP_NAME_CHARS: usize = 60;",
                  "MAX_GROUP_NAME_CHARS: usize = 80;")
        [line] = limits.problems(self.root)
        self.assertIn("l10n.newGroupName takes 60 characters", line)

    def test_a_dart_limit_changed_alone_fails(self):
        self.edit("app/lib/src/names.dart", "const maxBioChars = 190;", "const maxBioChars = 200;")
        self.assertEqual(len(limits.problems(self.root)), 1)

    def test_a_new_field_with_a_number_must_be_tied_to_a_rust_limit(self):
        self.field.write_text(self.field.read_text()
                              + "FgField(maxLength: 30, label: l10n.somethingNew);\n")
        [line] = limits.problems(self.root)
        self.assertIn("label l10n.somethingNew", line)


class VendorDiff(unittest.TestCase):
    def archive(self, *members):
        """A .crate (tar.gz) of (name, bytes) files and (name, "->target") links."""
        out = io.BytesIO()
        with tarfile.open(fileobj=out, mode="w:gz") as archive:
            for name, data in members:
                info = tarfile.TarInfo(name)
                if isinstance(data, str):
                    info.type, info.linkname = tarfile.SYMTYPE, data[2:]
                    archive.addfile(info)
                else:
                    info.size = len(data)
                    archive.addfile(info, io.BytesIO(data))
        return out.getvalue()

    def test_the_crate_is_unpacked_inside_its_folder_only(self):
        with tempfile.TemporaryDirectory() as tmp:
            into = pathlib.Path(tmp) / "x"
            vendor_diff.unpack(self.archive(("turn-1.0.0/src/lib.rs", b"code")), into,
                               "turn-1.0.0")
            self.assertEqual((into / "src/lib.rs").read_bytes(), b"code")
            for member in [("turn-1.0.0/../evil", b"x"), ("other/evil", b"x"),
                           ("/etc/evil", b"x"), ("turn-1.0.0/link", "->/etc/passwd")]:
                with self.subTest(member=member[0]):
                    with self.assertRaises(SystemExit):
                        vendor_diff.unpack(self.archive(member), pathlib.Path(tmp) / "y",
                                           "turn-1.0.0")
            self.assertFalse((pathlib.Path(tmp) / "evil").exists())

    def test_the_index_path_of_a_crate(self):
        self.assertEqual(vendor_diff.index_path("libp2p-quic"), "li/bp/libp2p-quic")
        self.assertEqual(vendor_diff.index_path("Turn"), "tu/rn/turn")
        self.assertEqual(vendor_diff.index_path("abc"), "3/a/abc")
        self.assertEqual(vendor_diff.index_path("ab"), "2/ab")

    def test_each_vendored_crate_says_what_it_changed(self):
        for folder in sorted((TOOLS.parent / "vendor").iterdir()):
            with self.subTest(crate=folder.name):
                self.assertTrue((folder / "FOGATA.md").is_file())
                name, version = vendor_diff.recorded(folder)
                self.assertIn(f"{name} {version}", (folder / "FOGATA.md").read_text())

    def test_a_dart_package_is_unpacked_from_its_top_only(self):
        with tempfile.TemporaryDirectory() as tmp:
            into = pathlib.Path(tmp) / "x"
            vendor_diff.unpack(self.archive(("lib/a.dart", b"code"), ("./pubspec.yaml", b"p")),
                               into, None)
            self.assertEqual((into / "lib/a.dart").read_bytes(), b"code")
            self.assertEqual((into / "pubspec.yaml").read_bytes(), b"p")
            for member in [("../evil", b"x"), ("/etc/evil", b"x"), ("lib/link", "->/etc/passwd")]:
                with self.subTest(member=member[0]):
                    with self.assertRaises(SystemExit):
                        vendor_diff.unpack(self.archive(member), pathlib.Path(tmp) / "y", None)
            self.assertFalse((pathlib.Path(tmp) / "evil").exists())

    def test_each_dart_fork_says_what_it_forked_and_pub_dev_is_read(self):
        forks = [f for f in sorted((TOOLS.parent / "app/third_party").iterdir())
                 if (f / "pubspec.yaml").is_file()]
        self.assertEqual([f.name for f in forks], ["desktop_drop", "flutter_webrtc", "tray_manager"])
        for folder in forks:
            with self.subTest(fork=folder.name):
                name, version = vendor_diff.pub_recorded(folder)
                self.assertEqual(name, folder.name)
                self.assertIn(version, (folder / "FOGATA.md").read_text())
        versions, newest = vendor_diff.pub_published({
            "latest": {"version": "1.6.3"},
            "versions": [{"version": "1.6.2+hotfix.4", "archive_url": "u1", "archive_sha256": "a"},
                         {"version": "1.6.3", "archive_url": "u2"}]})
        self.assertEqual(versions, {"1.6.2+hotfix.4": ("u1", "a"), "1.6.3": ("u2", None)})
        self.assertEqual(newest, "1.6.3")


class WebrtcStable(unittest.TestCase):
    BRANCHES = {158: "8127", 157: "8103", 156: "8078", 155: "8059"}
    COMMIT = "1" * 40

    def stable(self, milestone, webrtc=None):
        return {"milestone": milestone, "version": f"{milestone}.0.1.2", "platform": "Linux",
                "hashes": {"webrtc": webrtc or self.COMMIT}}

    def test_the_pins_are_read(self):
        milestone, branch, commit = check_stable.pinned(check_stable.PINS.read_text())
        self.assertEqual(self.BRANCHES.get(milestone, branch), branch)
        self.assertEqual(len(commit), 40)

    def test_how_far_behind_decides(self):
        pins = (156, "8078", self.COMMIT)
        self.assertEqual(check_stable.verdict(pins, self.stable(156), self.BRANCHES)[0], "ok")
        self.assertEqual(check_stable.verdict(pins, self.stable(156, "2" * 40),
                                              self.BRANCHES)[0], "warning")
        self.assertEqual(check_stable.verdict(pins, self.stable(157), self.BRANCHES)[0],
                         "warning")
        level, text = check_stable.verdict(pins, self.stable(158), self.BRANCHES)
        self.assertEqual(level, "error")
        self.assertIn("2 milestone(s) behind", text)
        # A branch-head that is not the milestone's is an error of the pins.
        self.assertEqual(check_stable.verdict((156, "8103", self.COMMIT), self.stable(156),
                                              self.BRANCHES)[0], "error")


class Deadlines(unittest.TestCase):
    """tools/beta/deadlines.py, which the weekly workflow runs: the dates after which
    something of the pre-releases breaks, failing well before each."""

    MANIFEST = b'{"format": 1, "version": "0.1.0-beta.8", "published": 1794355395, ' \
               b'"expires": 1809907395}'

    def test_a_release_s_expiry_is_read_from_its_manifest(self):
        version, when = deadlines.release_expiry(self.MANIFEST)
        self.assertEqual((version, f"{when:%Y-%m-%d %H:%M:%S}"),
                         ("0.1.0-beta.8", "2027-05-10 00:03:15"))
        with self.assertRaises(ValueError):
            deadlines.release_expiry(b'{"version": "x"}')

    def test_it_fails_a_month_before_and_warns_before_that(self):
        when = deadlines.parse_date("2027-05-10T00:03:15Z")
        dates = [(when, "it ends", "renew it")]
        for today, level in [("2026-11-11", "ok"), ("2027-03-01", "note"),
                             ("2027-04-12", "warn"), ("2027-06-01", "warn")]:
            with self.subTest(today=today):
                now = deadlines.parse_date(f"{today}T00:00:00Z")
                lines, found = deadlines.report(dates, now)
                self.assertEqual(found, level)
                self.assertIn("2027-05-10: it ends", lines[0])

    def test_the_newest_release_with_a_manifest_is_read_from_github(self):
        pages = {
            "https://api.github.com/repos/holypandadev/Fogata/releases?per_page=20": json.dumps([
                {"draft": True, "assets": [{"name": "release.json", "browser_download_url": "d"}]},
                {"draft": False, "assets": [{"name": "README.txt", "browser_download_url": "r"}]},
                {"draft": False, "prerelease": True,
                 "assets": [{"name": "release.json", "browser_download_url": "new"}]},
                {"draft": False, "assets": [{"name": "release.json", "browser_download_url": "old"}]},
            ]).encode(),
            "new": self.MANIFEST,
        }
        self.assertEqual(deadlines.newest_release_json(lambda url, token: pages[url]), self.MANIFEST)
        self.assertIsNone(deadlines.newest_release_json(lambda url, token: b"[]"))

    def test_every_date_is_well_formed(self):
        for when, what, todo in deadlines.DEADLINES:
            self.assertTrue(deadlines.parse_date(when) and what and todo)


class MacosWebrtc(unittest.TestCase):
    """The Mac app carries Fogata's WebRTC only: with Swift packages on, flutter_webrtc's
    package would add webrtc-sdk's beside it, and the build fails or ships the wrong one."""

    def test_swift_packages_are_off_for_the_app(self):
        pubspec = (TOOLS.parent / "app" / "pubspec.yaml").read_text()
        self.assertRegex(pubspec, r"\nflutter:\n(  .*\n|\s*#.*\n)*?  config:\n    enable-swift-package-manager: false\n")

    def test_no_swift_package_of_flutter_webrtc_brings_another_webrtc(self):
        # Without a Package.swift the plugin is built through its podspec, with Fogata's
        # WebRTC, even if the setting above were lost or renamed by a newer Flutter.
        plugin = TOOLS.parent / "app/third_party/flutter_webrtc"
        self.assertEqual(sorted(plugin.rglob("Package.swift")), [])
        for package in sorted((TOOLS.parent / "app/third_party").rglob("Package.swift")):
            with self.subTest(package=package):
                self.assertNotIn("binaryTarget", package.read_text())

    def test_the_two_darwin_copies_of_flutter_webrtc_are_the_same(self):
        # FOGATA.md's "both copies, identical": only the macOS copy is built.
        plugin = TOOLS.parent / "app/third_party/flutter_webrtc"
        common = plugin / "common/darwin/Classes"
        built = plugin / "macos/flutter_webrtc/Sources/flutter_webrtc"
        headers = built / "include/flutter_webrtc"
        shared = sorted((p.name, folder) for p in common.iterdir() for folder in (built, headers)
                        if (folder / p.name).is_file())
        self.assertIn(("FlutterWebRTCPlugin.m", built), shared)
        self.assertIn(("FlutterWebRTCPlugin.h", headers), shared)
        for name, folder in shared:
            with self.subTest(file=name):
                self.assertEqual((common / name).read_bytes(), (folder / name).read_bytes())


class Toolchains(unittest.TestCase):
    """What the builds are made with, the same everywhere."""

    def test_every_computer_builds_with_the_flutter_of_the_workflows(self):
        pubspec = (TOOLS.parent / "app/pubspec.yaml").read_text()
        environment = re.search(r"(?m)^environment:\n((?:  .*\n|\s*#.*\n)*)", pubspec)
        self.assertIsNotNone(environment)
        pinned = re.search(r"(?m)^  flutter: (\S+)$", environment.group(1))
        self.assertIsNotNone(pinned, "app/pubspec.yaml names no Flutter under environment:")
        # A bare version: pub then takes that Flutter only.
        self.assertRegex(pinned.group(1), r"^\d+\.\d+\.\d+$")
        named = {}
        for path in sorted((TOOLS.parent / ".github/workflows").glob("*.yml")):
            for version in re.findall(r"(?m)^  FLUTTER_VERSION: (\S+)$", path.read_text()):
                named[path.name] = version
        self.assertIn("ci.yml", named)
        self.assertIn("release-build.yml", named)
        self.assertEqual(set(named.values()), {pinned.group(1)}, named)

    def test_the_mac_builds_use_one_xcode(self):
        named = {}
        for name in ("ci.yml", "release-build.yml"):
            text = (TOOLS.parent / ".github/workflows" / name).read_text()
            found = re.findall(r'(?m)^  XCODE_VERSION: "(\d+(?:\.\d+)*)"$', text)
            self.assertEqual(len(found), 1, name)
            named[name] = found[0]
            self.assertIn("DEVELOPER_DIR=$xcode/Contents/Developer", text)
            self.assertIn("Use the CocoaPods of Podfile.lock", text)
        self.assertEqual(len(set(named.values())), 1, named)

    def test_every_build_is_checked_as_release_py_checks_it_and_recorded(self):
        workflows = TOOLS.parent / ".github/workflows"
        for name, systems in [("ci.yml", ["macos", "windows"]),
                              ("release-build.yml", ["linux", "macos", "windows"])]:
            text = (workflows / name).read_text()
            for system in systems:
                with self.subTest(workflow=name, system=system):
                    job = re.search(rf"(?ms)^  {system}:\n(.*?)(?=^  \S|\Z)", text).group(1)
                    self.assertRegex(job, rf"ci_builds\.py check-build {system} ")
                    self.assertIn(f"tools/toolchain.sh {system}", job)
                    self.assertRegex(job, rf"flutter build {system} --release")
                    self.assertNotIn("--debug", job)
        # The Linux job of ci.yml builds and checks through ci.sh.
        self.assertIn("tools/toolchain.sh linux", (workflows / "ci.yml").read_text())
        self.assertIn("ci_builds.py check-build linux app/build/linux/x64/release/bundle",
                      (TOOLS / "ci.sh").read_text())
        # The release builds keep the record beside each zip, outside it.
        release = (workflows / "release-build.yml").read_text()
        for system in ("linux", "windows", "macos"):
            self.assertRegex(release, rf"\n            toolchain-{system}\.txt\n")

    def test_ci_runs_both_halves_of_ci_sh_and_judges_each(self):
        # The Linux steps of tools/ci.sh run as two jobs side by side (--split): neither half
        # may go missing, and each job must judge its own record (ci.sh exits non-zero for
        # any split run, so the step that runs it may not fail the job by itself).
        text = (TOOLS.parent / ".github/workflows/ci.yml").read_text()
        runs = re.findall(r"(?m)^        run: (tools/ci\.sh .*)$", text)
        self.assertEqual(sorted(runs), ['tools/ci.sh --full --split app "$GITHUB_SHA"',
                                        'tools/ci.sh --full --split checks "$GITHUB_SHA"'])
        for half, job in (("app", "linux"), ("checks", "linux-checks")):
            with self.subTest(job=job):
                body = re.search(rf"(?ms)^  {job}:\n(.*?)(?=^  \S|\Z)", text).group(1)
                self.assertIn(f"--split {half}", body)
                self.assertIn(f"'split: {half}'", body)
                self.assertIn("- name: Judge the record", body)
                self.assertNotIn("needs:", body)
        checks = re.search(r"(?ms)^  linux-checks:\n(.*?)(?=^  \S|\Z)", text).group(1)
        for needed in ("'codegen: checked'", "'notices: checked'", "^advisories: checked",
                       "cargo deny fetch db", "FOGATA_FUZZ_TOOLCHAIN", "cargo-fuzz"):
            self.assertIn(needed, checks)

    def test_the_jni_plugin_is_never_built_on_linux_or_windows(self):
        # The jni package (an Android FFI plugin some dependency brings) builds a library
        # that needs Java wherever CMake finds a JDK, as on GitHub's computers: release.py
        # refused beta.8's bundles for it. Only the setting before the plugins' rules keeps
        # it out.
        for system in ("linux", "windows"):
            with self.subTest(system=system):
                text = (TOOLS.parent / "app" / system / "CMakeLists.txt").read_text()
                code = [line.split("#", 1)[0].strip() for line in text.splitlines()]
                disabled = [at for at, line in enumerate(code)
                            if re.fullmatch(r"set\(\s*CMAKE_DISABLE_FIND_PACKAGE_JNI\s+"
                                            r"(TRUE|ON|1)\s*\)", line)]
                plugins = [at for at, line in enumerate(code)
                           if re.fullmatch(r"include\(\s*flutter/generated_plugins\.cmake\s*\)",
                                           line)]
                self.assertEqual(len(plugins), 1)
                self.assertTrue(disabled and disabled[0] < plugins[0],
                                "CMAKE_DISABLE_FIND_PACKAGE_JNI must be set before "
                                "generated_plugins.cmake is included")
                self.assertFalse(any(re.match(r"(set|unset)\(\s*CMAKE_DISABLE_FIND_PACKAGE_JNI\b",
                                              line) and at > disabled[0]
                                     for at, line in enumerate(code[:plugins[0]])),
                                 "set again before the plugins")


class Workflows(unittest.TestCase):
    """The workflows in .github/workflows, as the repository's settings cannot enforce from a
    file: every action pinned by its full commit (a tag can be moved to other code), only the
    actions reviewed, a token that can only read (but for the one job that attests the
    release builds), and no checkout that keeps the token."""

    ACTIONS = {
        "actions/checkout", "actions/cache", "actions/cache/restore", "actions/cache/save",
        "actions/upload-artifact", "subosito/flutter-action", "taiki-e/install-action",
        "Swatinem/rust-cache",
        # The release builds' attestations (release-build.yml): a composite action around
        # actions/attest, which it pins by commit itself.
        "actions/attest-build-provenance",
    }
    # The only job whose token may do more than read, and exactly what it may do: take the
    # builds of its own run (actions: read) and have GitHub sign their attestations. It
    # checks out nothing and runs none of the build's code.
    WIDER = {("release-build.yml", "attest"): [
        "contents: read", "actions: read", "id-token: write", "attestations: write"]}

    def job_permissions(self, text):
        """Each job's own permissions, as {job: [lines]}; a permissions: that is not a list
        of its own lines (write-all, read-all) comes out as [that value]."""
        found = {}
        job = None
        lines = text.splitlines()
        for at, line in enumerate(lines):
            named = re.match(r"^  ([\w-]+):\s*$", line)
            if named:
                job = named.group(1)
            given = re.match(r"^([ \t]+)permissions:\s*(.*)$", line)
            if not given:
                continue
            if given.group(2):
                found[job] = [given.group(2)]
                continue
            indent = len(given.group(1))
            block = []
            for below in lines[at + 1:]:
                if len(below) - len(below.lstrip()) <= indent:
                    break
                block.append(below.strip())
            found[job] = block
        return found

    def workflows(self):
        found = sorted((TOOLS.parent / ".github/workflows").glob("*.yml"))
        self.assertTrue(found)
        return [(path.name, path.read_text()) for path in found]

    def test_actions_are_pinned_by_commit_and_reviewed(self):
        for name, text in self.workflows():
            for action, ref in re.findall(r"^\s*(?:-\s*)?uses:\s*([^@\s]+)@(\S+)", text, re.M):
                with self.subTest(workflow=name, action=action):
                    self.assertRegex(ref, r"^[0-9a-f]{40}$")
                    self.assertIn(action, self.ACTIONS)

    def test_the_token_only_reads_and_no_checkout_keeps_it(self):
        for name, text in self.workflows():
            with self.subTest(workflow=name):
                self.assertRegex(text, r"(?m)^permissions:\n  contents: read\n(?!  )")
                # No job widens it, but the one WIDER names, by exactly that.
                for job, given in self.job_permissions(text).items():
                    self.assertEqual(given, self.WIDER.get((name, job)), f"job {job}")
                self.assertNotIn("pull_request_target", text)
                checkouts = len(re.findall(r"uses: actions/checkout@", text))
                self.assertEqual(text.count("persist-credentials: false"), checkouts)

    def test_a_job_that_widens_the_token_fails(self):
        text = ("permissions:\n  contents: read\n\njobs:\n  build:\n    runs-on: x\n"
                "    permissions:\n      contents: write\n    steps:\n      - run: true\n"
                "  other:\n    permissions: write-all\n  attest:\n    permissions:\n"
                "      id-token: write\n")
        self.assertEqual(self.job_permissions(text), {
            "build": ["contents: write"], "other": ["write-all"], "attest": ["id-token: write"]})

    def test_the_attesting_job_runs_no_code_of_the_repository(self):
        text = (TOOLS.parent / ".github/workflows/release-build.yml").read_text()
        job = re.search(r"(?ms)^  attest:\n(.*?)(?=^  \S|\Z)", text).group(1)
        self.assertNotIn("actions/checkout", job)
        self.assertNotIn("tools/", job)
        self.assertIn("actions/attest-build-provenance@", job)


