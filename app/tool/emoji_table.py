#!/usr/bin/env python3
"""Writes lib/src/emoji_table.dart from Unicode's emoji-test.txt.

Usage: tool/emoji_table.py <emoji-test.txt> [max emoji version, default 13.0]

Only fully-qualified emoji up to the given version go in, since newer ones show as
empty boxes on systems whose emoji font is older (Windows 10 stops at 12.1, Windows 11
and macOS 11 at 13.x). Skin tone variants are left out: a `~` after an emoji says that
one modifier after its first code point gives the variants, and the picker makes them.
"""

import re
import sys
from pathlib import Path

GROUPS = {
    'Smileys & Emotion': 'people',
    'People & Body': 'people',
    'Animals & Nature': 'nature',
    'Food & Drink': 'food',
    'Activities': 'activities',
    'Travel & Places': 'travel',
    'Objects': 'objects',
    'Symbols': 'symbols',
    'Flags': 'flags',
}
TONES = ['1F3FB', '1F3FC', '1F3FD', '1F3FE', '1F3FF']
LINE = re.compile(
    r'^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E(\d+)\.(\d+)\s+(.+)$'
)


def main():
    source = Path(sys.argv[1]).read_text(encoding='utf-8')
    top = tuple(int(n) for n in (sys.argv[2] if len(sys.argv) > 2 else '13.0').split('.'))
    version = re.search(r'^# Version: (\S+)', source, re.M).group(1)
    copyright_line = re.search(r'^# (© \d+ Unicode.*)$', source, re.M).group(1)
    group = None
    entries = {key: [] for key in dict.fromkeys(GROUPS.values())}
    # Every emoji up to the version, toned ones too: a base is only marked when its
    # variants are as old as the version allows (handshake's came years after it).
    every = set()
    for raw in source.splitlines():
        if raw.startswith('# group: '):
            group = GROUPS.get(raw[len('# group: '):].strip())
            continue
        m = LINE.match(raw)
        if not m:
            continue
        points = m.group(1).split()
        if (int(m.group(2)), int(m.group(3))) > top:
            continue
        every.add(tuple(points))
        if group is None:
            continue
        if any(p in TONES for p in points):
            continue
        entries[group].append((points, m.group(4)))

    def toned(points):
        # One modifier after the first code point, its presentation selector dropped.
        rest = points[1:]
        if rest and rest[0] == 'FE0F':
            rest = rest[1:]
        return all(tuple([points[0], t] + rest) in every for t in TONES)

    out = [
        '// Generated by tool/emoji_table.py from Unicode\'s emoji-test.txt '
        f'(version {version}); do not edit.',
        f'// Emoji data {copyright_line}',
        '// Used under the Unicode License v3 (https://www.unicode.org/license.txt).',
        '',
        '/// Each category\'s emoji, one per line: the emoji, `~` when skin tones apply,',
        '/// a tab and its name.',
        'const emojiTable = <String, String>{',
    ]
    for key, items in entries.items():
        lines = []
        for points, name in items:
            text = ''.join(chr(int(p, 16)) for p in points)
            lines.append(f'{text}{"~" if toned(points) else ""}\t{name}')
        body = '\n'.join(lines).replace('\\', '\\\\').replace("'", "\\'")
        body = body.replace('\t', '\\t').replace('$', '\\$')
        out.append(f"  '{key}':")
        # One line of Dart per emoji keeps the file readable in a diff.
        parts = body.split('\n')
        for i, part in enumerate(parts):
            end = ',' if i == len(parts) - 1 else ''
            nl = '' if i == len(parts) - 1 else '\\n'
            out.append(f"      '{part}{nl}'{end}")
    out.append('};')
    out.append('')
    target = Path(__file__).resolve().parent.parent / 'lib' / 'src' / 'emoji_table.dart'
    target.write_text('\n'.join(out), encoding='utf-8')
    print(f'{target}: {sum(len(v) for v in entries.values())} emoji')


if __name__ == '__main__':
    main()
